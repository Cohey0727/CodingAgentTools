#!/usr/bin/env bash
# Shared settings resolution for the claude launchers, `bin/setup.sh`, the
# Makefile and the global-config generators.
#
# configs.jsonc at the repo root describes every provider: endpoint, models, and
# the tags that say which slot each model fills. Every value that may come from
# outside the file is written as "${NAME}", or "${NAME:-fallback}" where the file
# can carry a working default — so an API_KEY, a BASE_URL and a header value all
# read the same way, and the .env beside it (gitignored) holds what they resolve to.

COMMON_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ROOT_DIR=$(dirname "$COMMON_DIR")
MODELS_PY="$COMMON_DIR/models.py"
CONFIGS_FILE="$ROOT_DIR/configs.jsonc"
ENV_FILE="$ROOT_DIR/.env"
ENV_EXAMPLE="$ROOT_DIR/.env.example"
PYTHON="${PYTHON:-python3}"

# Every file this repo generates opens with this, so a hand-written one at the
# same path is recognised and left alone. The comment character differs by
# format — JSONC takes "//", TOML takes "#" — so the note is what identifies
# the file and the prefix only has to keep the line a comment. The rest of the
# line is guidance for whoever opens it.
GENERATED_NOTE="generated by claude-compatibles"
GENERATED_MARKER="// $GENERATED_NOTE"
GENERATED_MARKER_HASH="# $GENERATED_NOTE"

generated_marker() { # <target> [<comment prefix>] -> the first line of a config
                     # this repo writes, naming the target that rewrites it
  printf "%s — re-run 'make %s' after editing configs.jsonc" \
    "${2:-$GENERATED_MARKER}" "$1"
}

PI_GLOBAL_MARKER=$(generated_marker pi-global)
OPENCODE_GLOBAL_MARKER=$(generated_marker opencode-global)
CRUSH_GLOBAL_MARKER=$(generated_marker crush-global "$GENERATED_MARKER_HASH")
REASONIX_GLOBAL_MARKER=$(generated_marker reasonix-global "$GENERATED_MARKER_HASH")
CODEWHALE_GLOBAL_MARKER=$(generated_marker codewhale-global "$GENERATED_MARKER_HASH")
OPENCODE_PLUGIN_MARKER="$GENERATED_MARKER — the plugin itself lives in this repo"

generated_here() { # <file> — does it carry the note on its first line, under
                   # whichever comment character its format uses?
  [ -f "$1" ] || return 1
  case "$(head -1 "$1")" in
    "$GENERATED_MARKER"*|"$GENERATED_MARKER_HASH"*) return 0 ;;
    *) return 1 ;;
  esac
}

opencode_config_dir() { # -> OpenCode's global config directory
  printf '%s/opencode' "${XDG_CONFIG_HOME:-$HOME/.config}"
}

opencode_command_dir() { # -> where OpenCode reads global slash commands
  printf '%s/command' "$(opencode_config_dir)"
}

opencode_plugin_dir() { # -> where OpenCode loads global plugins
  printf '%s/plugin' "$(opencode_config_dir)"
}

opencode_global_config_path() { # -> the opencode.json `make opencode-global` writes
  printf '%s/opencode.json' "$(opencode_config_dir)"
}

opencode_tokens_dir() { # -> per-provider secret files the generated config references
  printf '%s/claude-compatibles' "$(opencode_config_dir)"
}

# The agent CLIs that get no launcher. Each has one generator under bin/ that
# writes that CLI's whole global config from configs.jsonc, and `make setup`
# runs them in this order; every one is also a make target of its own.
GLOBAL_GENERATORS="pi-global-models
opencode-global-config
crush-global-config
reasonix-global-config
codewhale-global-config"

# The path each of those owns, in the same order. Named here rather than in the
# Makefile so uninstall removes them all without spelling any of them out.
GENERATED_CONFIG_PATHS="pi_global_models_path
opencode_global_config_path
crush_global_config_path
reasonix_global_config_path
codewhale_global_config_path"

generated_config_paths() { # -> one generated config path per line
  local path
  while IFS= read -r path; do
    [ -n "$path" ] || continue
    printf '%s\n' "$("$path")"
  done <<<"$GENERATED_CONFIG_PATHS"
}

reasonix_home() { # -> Reasonix's own directory: its config and its .env
  printf '%s' "${REASONIX_HOME:-$HOME/.reasonix}"
}

reasonix_global_config_path() { # -> the config.toml `make reasonix-global` writes
  printf '%s/config.toml' "$(reasonix_home)"
}

reasonix_env_path() { # -> the only file Reasonix reads provider keys from
  printf '%s/.env' "$(reasonix_home)"
}

codewhale_home() { # -> Codewhale's own directory: its config and its .env
  printf '%s' "${CODEWHALE_HOME:-$HOME/.codewhale}"
}

codewhale_global_config_path() { # -> the config.toml `make codewhale-global` writes
  printf '%s/config.toml' "$(codewhale_home)"
}

crush_config_dir() { # -> Crush's global config directory
  printf '%s/crush' "${XDG_CONFIG_HOME:-$HOME/.config}"
}

crush_global_config_path() { # -> the crushrc `make crush-global` writes
  printf '%s/crushrc' "$(crush_config_dir)"
}

default_provider() { # <configured provider>... -> the one to start on. The name
                     # is whichever provider configs.jsonc marks "primary";
                     # falling back to the first configured one keeps a keyless
                     # checkout working.
  local p want
  want="${DEFAULT_PROVIDER:-$("$PYTHON" "$MODELS_PY" primary)}"
  for p in "$@"; do
    [ "$p" = "$want" ] && { printf '%s' "$p"; return 0; }
  done
  printf '%s' "$1"
}

# pi packages `make setup` installs, as "<source>=<slash command>" pairs. pi
# keeps its core small and ships no loop of its own: /loop repeats a prompt
# until a stop condition, /goal drives an objective across turns. Override to
# install a different set: PI_PACKAGES="npm:pi-reactor=/reactor" make setup
PI_PACKAGES="${PI_PACKAGES:-npm:@realvendex/pi-loop=/loop npm:pi-goal=/goal}"

pi_agent_dir() { # -> pi's agent directory: settings, auth, models, packages
  printf '%s' "${PI_CODING_AGENT_DIR:-$HOME/.pi/agent}"
}

pi_global_models_path() { # -> the models.json `make pi-global` writes
  printf '%s/models.json' "$(pi_agent_dir)"
}

pi_package_source() { # "npm:x=/cmd" -> "npm:x"
  printf '%s' "${1%%=*}"
}

pi_package_command() { # "npm:x=/cmd" -> "/cmd"; nothing when the pair has no command
  case $1 in *=*) printf '%s' "${1#*=}" ;; esac
}

pi_package_installed() { # <source> — recorded in pi's user settings?
  local settings
  settings="$(pi_agent_dir)/settings.json"
  [ -f "$settings" ] && grep -qF "\"$1\"" "$settings"
}

# --------------------------------------------------------------------- .env

# The .env is only ever read inside a subshell, so the caller's environment
# never carries one provider's key into another provider's process. It is
# sourced rather than parsed: a value may be computed, e.g. a short-lived
# Cloudflare Access token from $(cloudflared access token ...).
env_value() { # <variable name> [<fallback>] -> its value from the .env, or the
              # fallback when the variable is unset or empty
  (
    set -a
    # shellcheck disable=SC1090
    [ -f "$ENV_FILE" ] && . "$ENV_FILE"
    set +a
    printf '%s' "${!1:-${2:-}}"
  )
}

# ------------------------------------------------------------------- models

models_resolve() { # <provider> — set the M_* variables from configs.jsonc
  local resolved
  resolved=$(
    set -a
    # shellcheck disable=SC1090
    [ -f "$ENV_FILE" ] && . "$ENV_FILE"
    set +a
    "$PYTHON" "$MODELS_PY" sh "$1"
  ) || return 1
  eval "$resolved"
}

models_check() { # [<provider>] — validate configs.jsonc, print nothing on success
  "$PYTHON" "$MODELS_PY" check ${1:+"$1"}
}

models_tags() { # <provider> -> "<id><tab><tag>,<tag>" per model
  "$PYTHON" "$MODELS_PY" tags "$1"
}

provider_names() { # -> one provider name per line, in configs.jsonc order
  "$PYTHON" "$MODELS_PY" providers
}

provider_env_vars() { # -> "<provider><tab><var><tab><what>" per reference
  "$PYTHON" "$MODELS_PY" env-vars
}

provider_command() { # <provider> -> the launcher command, "claude<name>"
  ( models_resolve "$1" && printf '%s' "$M_COMMAND" )
}

provider_stale_commands() { # <provider> -> commands earlier versions installed
                            # for it; setup and uninstall remove them
  ( models_resolve "$1" && printf 'pi%s open%s' "$M_NAME" "$M_NAME" )
}

configured_provider() { # <provider> — valid, and its API_KEY resolves to something?
  ( models_resolve "$1" && [ -n "$M_API_KEY" ] )
}

require_settings() { # <launcher name> — fail fast on a key that resolved to nothing
  if [ -z "$M_API_KEY" ]; then
    echo "$1: API_KEY for '$M_NAME' is empty" >&2
    if [ -n "$M_API_KEY_VAR" ]; then
      echo "  set $M_API_KEY_VAR in $ENV_FILE, or run 'make setup'." >&2
    else
      echo "  set API_KEY for '$M_NAME' in $CONFIGS_FILE." >&2
    fi
    exit 1
  fi
}

model_rows() { # -> one "id US context US max_tokens US reasoning US input" line
               # per model, after models_resolve. Every generated config spells a
               # model differently, so each generator formats these itself.
  [ -n "$M_MODEL_ROWS" ] && printf '%s\n' "$M_MODEL_ROWS"
  return 0
}

# ------------------------------------------------------------------ dotenv

quote_env_value() { # <value> -> it, double-quoted when bash would not take it bare
  case $1 in
    ''|*[[:space:]\"\'\$\\]*) printf '"%s"' "${1//\"/\\\"}" ;;
    *) printf '%s' "$1" ;;
  esac
}

env_file_set() { # <file> <variable> <value> — rewrite its line, or append one,
                 # leaving every other line of the file alone. The file is a
                 # secret either way, so it is created and kept at 600.
  local file=$1 var=$2 value=$3 tmp line found=0
  mkdir -p "$(dirname "$file")"
  touch "$file"
  chmod 600 "$file"
  tmp=$(mktemp "${file}.XXXXXX")
  while IFS= read -r line || [ -n "$line" ]; do
    if [ "${line%%=*}" = "$var" ] && [ "$line" != "${line#*=}" ]; then
      printf '%s=%s\n' "$var" "$(quote_env_value "$value")"
      found=1
    else
      printf '%s\n' "$line"
    fi
  done < "$file" > "$tmp"
  if [ "$found" = 0 ]; then
    printf '%s=%s\n' "$var" "$(quote_env_value "$value")" >> "$tmp"
  fi
  chmod 600 "$tmp"
  mv "$tmp" "$file"
}

# ----------------------------------------------------------------- headers

# REQUEST_HEADERS reaches the shell as one "name US variable US fallback US
# value" line per header, US being \x1f. The separator is not whitespace on
# purpose: bash collapses runs of IFS whitespace into a single delimiter, so a
# tab-separated line with an empty field would shift every field after it.
# Claude Code takes the pairs as "Name: Value" lines; a generated config is
# given a reference instead, never a value resolved from the environment —
# except where the CLI's own format has no way to express one.
header_names() { # -> one header name per line
  local name rest
  [ -n "$M_HEADERS" ] || return 0
  while IFS=$'\x1f' read -r name rest; do
    [ -n "$name" ] && printf '%s\n' "$name"
  done <<<"$M_HEADERS"
}

header_field() { # <name> <field: var | fallback | value>
  local n var fallback value
  [ -n "$M_HEADERS" ] || return 0
  while IFS=$'\x1f' read -r n var fallback value; do
    [ "$n" = "$1" ] || continue
    case $2 in
      var) printf '%s' "$var" ;;
      fallback) printf '%s' "$fallback" ;;
      *) printf '%s' "$value" ;;
    esac
    return 0
  done <<<"$M_HEADERS"
}

header_var() { header_field "$1" var; }
header_fallback() { header_field "$1" fallback; }
header_value() { header_field "$1" value; }

claude_custom_headers() { # -> the "Name: Value" lines ANTHROPIC_CUSTOM_HEADERS takes
  local name out=''
  while IFS= read -r name; do
    [ -n "$name" ] || continue
    out="$out${out:+
}$name: $(header_value "$name")"
  done < <(header_names)
  printf '%s' "$out"
}

headers_json() { # <ref fn> -> `"Name": "<ref>"` members, comma-separated; empty
                 # when there are no headers. <ref fn> maps a header name to the
                 # reference written in place of its value.
  local name out=''
  while IFS= read -r name; do
    [ -n "$name" ] || continue
    out="$out${out:+,
}          \"$name\": \"$("$1" "$name")\""
  done < <(header_names)
  printf '%s' "$out"
}

# --------------------------------------------------------- generated configs

secret_command() { # <variable name> [<fallback>] -> a command that prints the
                   # value at the time it runs, so a generated config can carry
                   # the reference rather than the secret. The fallback goes in
                   # as a bare word, so a value that would need quoting inside
                   # the single-quoted command is refused; the caller writes the
                   # resolved literal instead.
  case ${2:-} in
    '') printf "bash -c '. %s; env_value %s'" "$COMMON_DIR/common.sh" "$1" ;;
    *[!A-Za-z0-9._:/-]*) return 1 ;;
    *) printf "bash -c '. %s; env_value %s %s'" "$COMMON_DIR/common.sh" "$1" "$2" ;;
  esac
}

pi_secret_ref() { # <variable name> [<fallback>] -> the same command, in the form
                  # pi takes a command in: a leading "!"
  local command
  command=$(secret_command "$1" "${2:-}") || return 1
  printf '!%s' "$command"
}

crush_secret_ref() { # <variable name> [<fallback>] -> the substitution Crush runs
                     # when it reads its config. crushrc is bash, so the command
                     # goes in as one.
  local command
  command=$(secret_command "$1" "${2:-}") || return 1
  printf '$(%s)' "$command"
}

codewhale_provider_id() { # -> the id Codewhale files the provider under. It
                          # ships a catalog of its own too, and only an id
                          # outside it may declare its own wire protocol.
  printf '%s-anthropic' "$M_NAME"
}

crush_provider_id() { # -> the id Crush files the provider under. Crush ships its
                      # own catalog of providers and merges an entry into the one
                      # whose id matches, so a locally declared provider takes a
                      # suffix and stays a provider of its own.
  printf '%s-anthropic' "$M_NAME"
}

pi_provider_json() { # <provider> <apiKey reference> [<header ref fn>] — one
                     # models.json provider block, after models_resolve. HEADERS
                     # are included when a reference function is given.
  local id=$1 api_key=$2 headers=''
  if [ -n "${3:-}" ] && [ -n "$M_HEADERS" ]; then
    headers="      \"headers\": {
$(headers_json "$3")
      },
"
  fi
  cat <<EOF
    "$id": {
      "baseUrl": "$M_BASE_URL",
      "api": "anthropic-messages",
      "apiKey": "$api_key",
${headers}      "models": [
$M_PI_MODELS_JSON
      ]
    }
EOF
}

# Tools a lean agent drops. Only names OpenCode actually registers may appear
# here: denying a tool it does not know takes edit and write down with it.
OPENCODE_LEAN_DISABLED_TOOLS="skill task todowrite webfetch"

opencode_agent_json() { # <provider> <prompt file> — the lean agent for a provider
                        # whose server is too slow to prefill the stock request.
                        # "prompt" replaces the model-specific base prompt
                        # outright, and the denied tools are dropped from the
                        # request rather than merely refused.
  local name=$1 prompt=$2 tools='' t
  for t in $OPENCODE_LEAN_DISABLED_TOOLS; do
    tools="$tools${tools:+, }\"$t\": false"
  done
  cat <<EOF
    "$name": {
      "description": "$name with a short prompt and core tools only",
      "mode": "primary",
      "model": "$(opencode_provider_id)/$M_DEFAULT_MODEL",
      "prompt": "{file:$prompt}",
      "tools": { $tools }
    }
EOF
}

opencode_provider_id() { # -> the id OpenCode files the resolved provider under.
                         # The suffix keeps it apart from any provider of the
                         # same name in OpenCode's own catalog, whose definition
                         # would otherwise be merged into this one.
  printf '%s-anthropic' "$M_NAME"
}

# The heading every provider from configs.jsonc shares in OpenCode's model
# dialog, which groups by display name. OpenCode's own services keep headings of
# their own, and the dialog pins OpenCode Zen to the top.
OPENCODE_PROVIDER_HEADING="Subscriptions"

opencode_provider_json() { # <apiKey reference> [<header ref fn>] — one provider
                           # block. The key and the header values are only ever
                           # referenced ({file:...}).
  local api_key=$1 headers=''
  if [ -n "${2:-}" ] && [ -n "$M_HEADERS" ]; then
    headers=",
        \"headers\": {
$(headers_json "$2")
        }"
  fi

  # The AI SDK Anthropic provider appends "/messages" to its baseURL, while
  # BASE_URL is the Claude Code form that gets "/v1/messages" appended — so
  # baseURL is BASE_URL plus "/v1".
  cat <<EOF
    "$(opencode_provider_id)": {
      "npm": "@ai-sdk/anthropic",
      "name": "$OPENCODE_PROVIDER_HEADING",
      "options": {
        "baseURL": "$M_BASE_URL/v1",
        "apiKey": "$api_key"$headers
      },
      "models": {
$M_OPENCODE_MODELS_JSON
      }
    }
EOF
}
