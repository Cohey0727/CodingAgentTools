#!/usr/bin/env bash
# Shared settings resolution for the claude/pi launchers, `bin/setup.sh`, the
# Makefile and the global-config generators.
#
# A provider's .env holds one set of generic settings (API_TOKEN, BASE_URL,
# MODEL, SMALL_MODEL, ...) that Claude Code, OpenCode and pi all run on.
# Every generic setting has CLI-specific override names that win when set;
# each launcher applies its own after calling load_settings.

# First line of a models.json written by `make pi-global`. pi strips JSON
# comments, so the file stays valid; nothing without this line is touched.
PI_GLOBAL_MARKER="// generated by claude-compatibles — re-run 'make pi-global' after editing any .env"

# First line of the opencode.json written by `make opencode-global`. OpenCode
# parses JSONC, so the file stays valid; nothing without this line is touched.
OPENCODE_GLOBAL_MARKER="// generated by claude-compatibles — re-run 'make opencode-global' after editing any .env"

# First line of the plugin shims `make setup-skills` writes into OpenCode's
# plugin directory. Nothing without this line is touched.
OPENCODE_PLUGIN_MARKER="// generated by claude-compatibles — the plugin itself lives in this repo"

opencode_config_dir() { # -> OpenCode's global config directory
  printf '%s/opencode' "${XDG_CONFIG_HOME:-$HOME/.config}"
}

opencode_command_dir() { # -> where OpenCode reads global slash commands
  printf '%s/command' "$(opencode_config_dir)"
}

opencode_plugin_dir() { # -> where OpenCode loads global plugins
  printf '%s/plugin' "$(opencode_config_dir)"
}

opencode_global_config_path() { # -> the opencode.json `make opencode-global` writes
  printf '%s/opencode.json' "$(opencode_config_dir)"
}

opencode_tokens_dir() { # -> per-provider token files the generated config references
  printf '%s/claude-compatibles' "$(opencode_config_dir)"
}

# Provider the generated pi and OpenCode configs start on. Both fall back to
# the first configured provider (alphabetical) when this one has no token, so
# a checkout without it still gets a working default:
# DEFAULT_PROVIDER=gtr make setup
DEFAULT_PROVIDER="${DEFAULT_PROVIDER:-glm}"

default_provider() { # <configured provider>... -> the one to start on
  local p
  for p in "$@"; do
    [ "$p" = "$DEFAULT_PROVIDER" ] && { printf '%s' "$p"; return 0; }
  done
  printf '%s' "$1"
}

# pi packages `make setup` installs, as "<source>=<slash command>" pairs. pi
# keeps its core small and ships no loop of its own: /loop repeats a prompt
# until a stop condition, /goal drives an objective across turns. Override to
# install a different set: PI_PACKAGES="npm:pi-reactor=/reactor" make setup
PI_PACKAGES="${PI_PACKAGES:-npm:@realvendex/pi-loop=/loop npm:pi-goal=/goal}"

pi_agent_dir() { # -> pi's agent directory: settings, auth, models, packages
  printf '%s' "${PI_CODING_AGENT_DIR:-$HOME/.pi/agent}"
}

pi_global_models_path() { # -> the models.json `make pi-global` writes
  printf '%s/models.json' "$(pi_agent_dir)"
}

pi_package_source() { # "npm:x=/cmd" -> "npm:x"
  printf '%s' "${1%%=*}"
}

pi_package_command() { # "npm:x=/cmd" -> "/cmd"; nothing when the pair has no command
  case $1 in *=*) printf '%s' "${1#*=}" ;; esac
}

pi_package_installed() { # <source> — recorded in pi's user settings?
  local settings
  settings="$(pi_agent_dir)/settings.json"
  [ -f "$settings" ] && grep -qF "\"$1\"" "$settings"
}

pick() { # <var name>... -> value of the first one that is set and non-empty
  local name
  for name in "$@"; do
    if [ -n "${!name:-}" ]; then printf '%s' "${!name}"; return 0; fi
  done
}

launcher_name() { # <provider dir name> -> "claude<name>"
  printf '%s' "${COMMAND:-claude${NAME:-$1}}"
}

stale_launcher_names() { # <provider dir name> -> commands earlier versions
                         # installed for it; setup and uninstall remove them
  local suffix="${NAME:-$1}"
  printf '%s %s' "pi$suffix" "open$suffix"
}

unset_provider_settings() { # every name the .env schema defines, generic settings and
                            # overrides alike. The overrides are a feature of the .env
                            # file, not of the environment: a value inherited from the
                            # surrounding shell (e.g. a launcher-spawned agent session
                            # exports ANTHROPIC_BASE_URL) must not beat the file, or
                            # every provider resolves to the outermost one.
  unset NAME API_TOKEN BASE_URL MODEL SMALL_MODEL ARGS
  unset CONTEXT_WINDOW MAX_TOKENS SMALL_CONTEXT_WINDOW SMALL_MAX_TOKENS
  unset REASONING INPUT HEADERS
  unset COMMAND CLAUDE_ARGS CLAUDE_MODEL_SUFFIX
  unset OPENCODE_MODEL OPENCODE_SMALL_MODEL PI_MODEL PI_SMALL_MODEL
  unset OPENCODE_LEAN OPENCODE_CONTEXT_WINDOW OPENCODE_MAX_TOKENS
  unset ANTHROPIC_AUTH_TOKEN ANTHROPIC_BASE_URL ANTHROPIC_CUSTOM_HEADERS ANTHROPIC_MODEL
  unset ANTHROPIC_DEFAULT_OPUS_MODEL ANTHROPIC_DEFAULT_SONNET_MODEL
  unset ANTHROPIC_DEFAULT_HAIKU_MODEL ANTHROPIC_DEFAULT_FABLE_MODEL
  unset CLAUDE_CODE_SUBAGENT_MODEL CLAUDE_CODE_AUTO_COMPACT_WINDOW
}

load_settings() { # <env file> — export it verbatim, then resolve CFG_* from it
  unset_provider_settings
  set -a
  # shellcheck disable=SC1090
  source "$1"
  set +a

  CFG_TOKEN=$(pick ANTHROPIC_AUTH_TOKEN API_TOKEN)
  CFG_BASE_URL=$(pick ANTHROPIC_BASE_URL BASE_URL)
  while [[ "$CFG_BASE_URL" == */ ]]; do CFG_BASE_URL="${CFG_BASE_URL%/}"; done

  CFG_ARGS="${ARGS:-}"
  CFG_MODEL="${MODEL:-}"
  CFG_SMALL_MODEL=$(pick SMALL_MODEL MODEL)
  # "[1m]" is a Claude Code-only marker; the other CLIs send ids verbatim.
  CFG_MODEL_PLAIN="${CFG_MODEL%\[1m\]}"
  CFG_SMALL_MODEL_PLAIN="${CFG_SMALL_MODEL%\[1m\]}"

  CFG_CONTEXT_WINDOW="${CONTEXT_WINDOW:-}"
  CFG_MAX_TOKENS="${MAX_TOKENS:-}"
  CFG_SMALL_CONTEXT_WINDOW=$(pick SMALL_CONTEXT_WINDOW CONTEXT_WINDOW)
  CFG_SMALL_MAX_TOKENS=$(pick SMALL_MAX_TOKENS MAX_TOKENS)
  CFG_REASONING="${REASONING:-true}"
  CFG_INPUT="${INPUT:-text}"
  CFG_HEADERS="${HEADERS:-}"
}

# HEADERS holds extra request headers as "Name: Value" lines — the format
# Claude Code's ANTHROPIC_CUSTOM_HEADERS takes. OpenCode and pi get the same
# pairs as a JSON "headers" object whose values are references (an
# environment variable, a file, a command), never the values themselves.
header_names() { # -> one header name per line
  local line
  while IFS= read -r line; do
    line="${line#"${line%%[![:space:]]*}"}"
    [[ "$line" == *:* ]] || continue
    printf '%s\n' "${line%%:*}"
  done <<<"$CFG_HEADERS"
}

header_value() { # <name> -> its value, surrounding whitespace dropped
  local line
  while IFS= read -r line; do
    line="${line#"${line%%[![:space:]]*}"}"
    [ "${line%%:*}" = "$1" ] || continue
    line="${line#*:}"
    line="${line#"${line%%[![:space:]]*}"}"
    printf '%s' "${line%"${line##*[![:space:]]}"}"
    return 0
  done <<<"$CFG_HEADERS"
}

header_env_name() { # <name> -> the environment variable a launcher exports it as
  printf 'PROVIDER_HEADER_%s' "$(printf '%s' "$1" | tr -c 'A-Za-z0-9' '_' | tr 'a-z' 'A-Z')"
}

headers_json() { # <ref fn> -> `"Name": "<ref>"` members, comma-separated; empty
                 # when HEADERS is. <ref fn> maps a header name to the reference
                 # written in place of its value.
  local name out=''
  while IFS= read -r name; do
    [ -n "$name" ] || continue
    out="$out${out:+,
}          \"$name\": \"$("$1" "$name")\""
  done < <(header_names)
  printf '%s' "$out"
}

require_settings() { # <launcher name> <env file> — fail fast on missing basics
  local name=$1 file=$2
  if [ -z "$CFG_TOKEN" ]; then
    echo "$name: API_TOKEN is empty in $file" >&2
    echo "  edit the file and set your API key." >&2
    exit 1
  fi
  if [ -z "$CFG_BASE_URL" ]; then
    echo "$name: BASE_URL is empty in $file" >&2
    exit 1
  fi
  if [ -z "$CFG_MODEL" ]; then
    echo "$name: MODEL is empty in $file" >&2
    exit 1
  fi
}

pi_resolve() { # after load_settings: pi's view of the settings, overrides applied
  PI_CFG_MODEL="${PI_MODEL:-$CFG_MODEL_PLAIN}"
  PI_CFG_MODEL="${PI_CFG_MODEL%\[1m\]}"
  PI_CFG_SMALL_MODEL="${PI_SMALL_MODEL:-$CFG_SMALL_MODEL_PLAIN}"
  PI_CFG_SMALL_MODEL="${PI_CFG_SMALL_MODEL%\[1m\]}"

  # pi assumes 128k context / 16k output for models it does not know and caps
  # each request at maxTokens/3, so both limits are always written out.
  PI_CFG_CONTEXT_WINDOW="${CFG_CONTEXT_WINDOW:-200000}"
  PI_CFG_MAX_TOKENS="${CFG_MAX_TOKENS:-32768}"
  PI_CFG_SMALL_CONTEXT_WINDOW="${CFG_SMALL_CONTEXT_WINDOW:-$PI_CFG_CONTEXT_WINDOW}"
  PI_CFG_SMALL_MAX_TOKENS="${CFG_SMALL_MAX_TOKENS:-$PI_CFG_MAX_TOKENS}"

  if [ "$CFG_REASONING" = "true" ]; then PI_CFG_REASONING=true; else PI_CFG_REASONING=false; fi
  case ",$CFG_INPUT," in
    *,image,*) PI_CFG_INPUT='["text", "image"]' ;;
    *)         PI_CFG_INPUT='["text"]' ;;
  esac
}

pi_provider_json() { # <provider id> <apiKey reference> [<header ref fn>] — one
                     # models.json provider block; HEADERS are included when a
                     # reference function is given (see headers_json)
  local id=$1 api_key=$2 models headers=''
  models=$(pi_model_json "$PI_CFG_MODEL" "$PI_CFG_CONTEXT_WINDOW" "$PI_CFG_MAX_TOKENS")
  if [ "$PI_CFG_SMALL_MODEL" != "$PI_CFG_MODEL" ]; then
    models="$models,
$(pi_model_json "$PI_CFG_SMALL_MODEL" "$PI_CFG_SMALL_CONTEXT_WINDOW" "$PI_CFG_SMALL_MAX_TOKENS")"
  fi
  if [ -n "${3:-}" ] && [ -n "$CFG_HEADERS" ]; then
    headers="      \"headers\": {
$(headers_json "$3")
      },
"
  fi
  cat <<EOF
    "$id": {
      "baseUrl": "$CFG_BASE_URL",
      "api": "anthropic-messages",
      "apiKey": "$api_key",
${headers}      "models": [
$models
      ]
    }
EOF
}

pi_model_json() { # <model id> <context window> <max tokens>
  cat <<EOF
        {
          "id": "$1",
          "reasoning": $PI_CFG_REASONING,
          "input": $PI_CFG_INPUT,
          "contextWindow": $2,
          "maxTokens": $3
        }
EOF
}

opencode_resolve() { # after load_settings: OpenCode's view, overrides applied
  OC_CFG_MODEL="${OPENCODE_MODEL:-$CFG_MODEL_PLAIN}"
  OC_CFG_MODEL="${OC_CFG_MODEL%\[1m\]}"
  OC_CFG_SMALL_MODEL="${OPENCODE_SMALL_MODEL:-$CFG_SMALL_MODEL_PLAIN}"
  OC_CFG_SMALL_MODEL="${OC_CFG_SMALL_MODEL%\[1m\]}"

  # OpenCode compacts a session once it fills the context, so this is the
  # window it may grow into, not the server's capacity. A backend slow enough
  # to make a full window unusable sets OPENCODE_CONTEXT_WINDOW below it.
  OC_CFG_CONTEXT_WINDOW=$(pick OPENCODE_CONTEXT_WINDOW CFG_CONTEXT_WINDOW)
  OC_CFG_CONTEXT_WINDOW="${OC_CFG_CONTEXT_WINDOW:-200000}"
  OC_CFG_MAX_TOKENS=$(pick OPENCODE_MAX_TOKENS CFG_MAX_TOKENS)
  OC_CFG_MAX_TOKENS="${OC_CFG_MAX_TOKENS:-32768}"
  OC_CFG_SMALL_CONTEXT_WINDOW=$(pick OPENCODE_CONTEXT_WINDOW CFG_SMALL_CONTEXT_WINDOW)
  OC_CFG_SMALL_CONTEXT_WINDOW="${OC_CFG_SMALL_CONTEXT_WINDOW:-$OC_CFG_CONTEXT_WINDOW}"
  OC_CFG_SMALL_MAX_TOKENS=$(pick OPENCODE_MAX_TOKENS CFG_SMALL_MAX_TOKENS)
  OC_CFG_SMALL_MAX_TOKENS="${OC_CFG_SMALL_MAX_TOKENS:-$OC_CFG_MAX_TOKENS}"

  if [ "${OPENCODE_LEAN:-}" = "true" ]; then OC_CFG_LEAN=true; else OC_CFG_LEAN=false; fi
}

opencode_model_json() { # <model id> <context window> <max tokens>
  printf '        "%s": { "limit": { "context": %s, "output": %s } }' "$1" "$2" "$3"
}

# Tools a lean agent drops. Only names OpenCode actually registers may appear
# here: denying a tool it does not know takes edit and write down with it.
OPENCODE_LEAN_DISABLED_TOOLS="skill task todowrite webfetch"

opencode_agent_json() { # <provider name> <prompt file> — the lean agent for a
                        # provider whose server is too slow to prefill the stock
                        # request. "prompt" replaces the model-specific base
                        # prompt outright, and the denied tools are dropped from
                        # the request rather than merely refused.
  local name=$1 prompt=$2 tools='' t
  for t in $OPENCODE_LEAN_DISABLED_TOOLS; do
    tools="$tools${tools:+, }\"$t\": false"
  done
  cat <<EOF
    "$name": {
      "description": "$name with a short prompt and core tools only",
      "mode": "primary",
      "model": "$name-anthropic/$OC_CFG_MODEL",
      "prompt": "{file:$prompt}",
      "tools": { $tools }
    }
EOF
}

opencode_provider_json() { # <provider name> <apiKey reference> [<header ref fn>]
                           # — one provider block, id "<name>-anthropic". The AI
                           # SDK Anthropic provider appends "/messages" to its
                           # baseURL, while BASE_URL is the Claude Code form
                           # that gets "/v1/messages" appended — so baseURL is
                           # BASE_URL plus "/v1". The token and the HEADERS
                           # values are only ever referenced ({file:...}),
                           # never written into the config.
  local name=$1 api_key=$2 models headers=''
  models=$(opencode_model_json "$OC_CFG_MODEL" "$OC_CFG_CONTEXT_WINDOW" "$OC_CFG_MAX_TOKENS")
  if [ "$OC_CFG_SMALL_MODEL" != "$OC_CFG_MODEL" ]; then
    models="$models,
$(opencode_model_json "$OC_CFG_SMALL_MODEL" "$OC_CFG_SMALL_CONTEXT_WINDOW" "$OC_CFG_SMALL_MAX_TOKENS")"
  fi
  if [ -n "${3:-}" ] && [ -n "$CFG_HEADERS" ]; then
    headers=",
        \"headers\": {
$(headers_json "$3")
        }"
  fi
  cat <<EOF
    "$name-anthropic": {
      "npm": "@ai-sdk/anthropic",
      "name": "$name",
      "options": {
        "baseURL": "$CFG_BASE_URL/v1",
        "apiKey": "$api_key"$headers
      },
      "models": {
$models
      }
    }
EOF
}

strip_metadata() { # drop every launcher-only setting from the exported env
  unset NAME API_TOKEN BASE_URL MODEL SMALL_MODEL ARGS
  unset CONTEXT_WINDOW MAX_TOKENS SMALL_CONTEXT_WINDOW SMALL_MAX_TOKENS
  unset REASONING INPUT HEADERS
  unset COMMAND CLAUDE_ARGS CLAUDE_MODEL_SUFFIX
  unset OPENCODE_MODEL OPENCODE_SMALL_MODEL
  unset OPENCODE_LEAN OPENCODE_CONTEXT_WINDOW OPENCODE_MAX_TOKENS
  unset PI_MODEL PI_SMALL_MODEL
}

